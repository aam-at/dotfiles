ANSI_NAMES = ("black", "red", "green", "yellow", "blue", "magenta", "cyan", "white")
HEX_COLOR = re.compile(r"^#[0-9a-fA-F]{6}$")
REPO_ROOT = Path(__file__).resolve().parent.parent

# Structural neutrals from the extended Gruvbox grey ramp. These sit between
# background/foreground/selection and aren't semantic accents, so they're not
# part of palette.toml's schema — kept here as fixed constants instead.
NEUTRAL = {
    "bg3": "#665c54",
    "bg4": "#7c6f64",
    "fg3": "#bdae93",
}

# Icon and cursor themes are user choices, not palette colors, but GTK's
# settings.ini and dconf both have to name them and disagreeing copies are how
# the theme drifted last time. Single source of truth, edited by hand.
ICON_THEME = "elementary"
CURSOR_THEME = "sweet-cursors"


def fail(message: str) -> "NoReturn":
    raise ValueError(message)


def color(value: object, label: str) -> str:
    if not isinstance(value, str) or not HEX_COLOR.fullmatch(value):
        fail(f"{label} must be a #RRGGBB color, got {value!r}")
    return value.lower()


def load_palette(path: Path) -> dict[str, object]:
    try:
        data = tomllib.loads(path.read_text())
    except (OSError, tomllib.TOMLDecodeError) as exc:
        fail(f"cannot read {path}: {exc}")

    required = (
        "background",
        "foreground",
        "selection_background",
        "selection_foreground",
        "cursor",
        "cursor_text",
    )
    for key in required:
        color(data.get(key), key)

    ansi = data.get("ansi")
    if not isinstance(ansi, dict):
        fail("ansi must be a table with normal and bright tables")
    for intensity in ("normal", "bright"):
        table = ansi.get(intensity)
        if not isinstance(table, dict):
            fail(f"ansi.{intensity} must be a table")
        for name in ANSI_NAMES:
            color(table.get(name), f"ansi.{intensity}.{name}")

    data["name"] = str(data.get("name", path.stem))
    return data


def get(palette: dict[str, object], key: str) -> str:
    return color(palette[key], key)


def ansi(palette: dict[str, object], intensity: str, name: str) -> str:
    table = palette["ansi"][intensity]
    return color(table[name], f"ansi.{intensity}.{name}")


def all_ansi(palette: dict[str, object]) -> list[str]:
    return [
        ansi(palette, intensity, name)
        for intensity in ("normal", "bright")
        for name in ANSI_NAMES
    ]


def render_kitty(p: dict[str, object]) -> str:
    def line(key: str, value: str) -> str:
        return f"{key:<24}{value}"

    lines = [
        f"## name: {p['name']}",
        "",
        line("selection_foreground", get(p, "selection_foreground")),
        line("selection_background", get(p, "selection_background")),
        "",
        line("background", get(p, "background")),
        line("foreground", get(p, "foreground")),
        "",
    ]
    lines += [line(f"color{i}", value) for i, value in enumerate(all_ansi(p))]
    lines += [
        "",
        line("cursor", get(p, "cursor")),
        line("cursor_text_color", get(p, "cursor_text")),
        "",
        line("url_color", ansi(p, "normal", "blue")),
        "",
        "# START_AUTOGENERATED_TAB_STYLE",
        "# Feel free to update these colors manually and remove these comments.",
        line("active_tab_foreground", get(p, "selection_foreground")),
        line("active_tab_background", get(p, "selection_background")),
        line("inactive_tab_foreground", get(p, "foreground")),
        line("inactive_tab_background", get(p, "background")),
        "# END_AUTOGENERATED_TAB_STYLE",
    ]
    return "\n".join(lines) + "\n"


def render_ghostty(p: dict[str, object]) -> str:
    lines = ["# Generated from palette.toml; Ghostty theme adapter."]
    lines += [f"palette = {i}={value}" for i, value in enumerate(all_ansi(p))]
    lines += [
        f"background = {get(p, 'background')}",
        f"foreground = {get(p, 'foreground')}",
        f"cursor-color = {get(p, 'cursor')}",
        f"cursor-text = {get(p, 'cursor_text')}",
        f"selection-background = {get(p, 'selection_background')}",
        f"selection-foreground = {get(p, 'selection_foreground')}",
    ]
    return "\n".join(lines) + "\n"


def render_alacritty(p: dict[str, object]) -> str:
    def section(name: str, values: dict[str, str]) -> list[str]:
        return [f"[colors.{name}]"] + [
            f'{key} = "{value}"' for key, value in values.items()
        ]

    lines = ["# Generated from palette.toml; Alacritty color adapter."]
    lines += section(
        "primary",
        {"background": get(p, "background"), "foreground": get(p, "foreground")},
    )
    lines += [""] + section(
        "cursor", {"text": get(p, "cursor_text"), "cursor": get(p, "cursor")}
    )
    lines += [""] + section(
        "selection",
        {
            "text": get(p, "selection_foreground"),
            "background": get(p, "selection_background"),
        },
    )
    for intensity in ("normal", "bright"):
        lines += [""] + section(
            intensity, {name: ansi(p, intensity, name) for name in ANSI_NAMES}
        )
    return "\n".join(lines) + "\n"


