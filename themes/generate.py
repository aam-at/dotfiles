"""Generate application theme adapters from a canonical palette.toml.

Usage:
    themes/generate.py themes/gruvbox-dark/palette.toml
    themes/generate.py palette.toml --output-dir /tmp/generated-theme
    themes/generate.py palette.toml --check

The input schema is intentionally small and application-neutral. See
themes/gruvbox-dark/palette.toml for an example.
"""

