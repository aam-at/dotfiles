def patch_markers(text: str, blocks: dict[str, str]) -> str:
    for name, body in blocks.items():
        start = f"# START_AUTOGENERATED_{name}"
        end = f"# END_AUTOGENERATED_{name}"
        # Capture whatever indentation precedes the end marker so it survives
        # the replacement (YAML/tmux blocks may nest it under indented keys).
        pattern = re.compile(
            re.escape(start) + r".*?([ \t]*)" + re.escape(end), re.DOTALL
        )
        match = pattern.search(text)
        if not match:
            fail(f"missing {name} marker block")
        indent = match.group(1)
        replacement = f"{start}\n{body}\n{indent}{end}"
        text, count = pattern.subn(lambda _m, r=replacement: r, text, count=1)
        if count != 1:
            fail(f"expected exactly one {name} marker block, found {count}")
    return text


