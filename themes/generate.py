def render_dms(p: dict[str, object]) -> str:
    normal = {name: ansi(p, "normal", name) for name in ANSI_NAMES}
    bright = {name: ansi(p, "bright", name) for name in ANSI_NAMES}

    def scheme(name: str, light: bool = False) -> dict[str, str]:
        return {
            "name": name,
            "primary": get(p, "selection_background"),
            "primaryText": get(p, "background"),
            "primaryContainer": get(p, "selection_background"),
            "secondary": bright["blue"],
            "surface": get(p, "background"),
            "surfaceText": get(p, "foreground"),
            "surfaceVariant": normal["black"],
            "surfaceVariantText": normal["white"],
            "surfaceTint": get(p, "selection_background"),
            "background": get(p, "background"),
            "backgroundText": get(p, "foreground"),
            "outline": bright["black"],
            "surfaceContainer": get(p, "background"),
            "surfaceContainerHigh": normal["black"],
            "surfaceContainerHighest": normal["black"],
            "error": bright["red"] if not light else normal["red"],
            "warning": bright["yellow"] if not light else normal["yellow"],
            "info": bright["blue"] if not light else normal["blue"],
            "matugen_type": "scheme-expressive",
        }

    return (
        json.dumps(
            {
                "dark": scheme(str(p["name"])),
                "light": scheme(f"{p['name']} (light fallback)", light=True),
            },
            indent=2,
        )
        + "\n"
    )


def mix(hex_a: str, hex_b: str, weight: float) -> str:
    """Blend hex_a toward hex_b; weight 0.0 keeps a, 1.0 returns b."""
    channels = (
        round(
            int(hex_a[i : i + 2], 16) * (1 - weight)
            + int(hex_b[i : i + 2], 16) * weight
        )
        for i in (1, 3, 5)
    )
    return "#" + "".join(f"{c:02x}" for c in channels)


