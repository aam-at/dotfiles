def recolor_yazi(original: str, p: dict[str, object]) -> str:
    """Yazi's theme.toml mixes color values with static nerd-font glyphs and
    icon/extension lists. Rather than reconstructing the whole file from a
    template (risking mangling the glyphs), swap only the hex values that are
    already known to represent each palette role in this file, via a
    placeholder pass so a new value can never collide with an old one still
    waiting to be replaced."""
    n = {name: ansi(p, "normal", name) for name in ANSI_NAMES}
    b = {name: ansi(p, "bright", name) for name in ANSI_NAMES}
    roles = [
        ("#282828", get(p, "background")),
        ("#d5c4a1", get(p, "foreground")),
        ("#504945", get(p, "selection_background")),
        ("#3c3836", n["black"]),
        ("#665c54", NEUTRAL["bg3"]),
        ("#83a598", b["blue"]),
        ("#8ec07c", b["cyan"]),
        ("#fabd2f", b["yellow"]),
        ("#fb4934", b["red"]),
        ("#b8bb26", b["green"]),
        ("#d3869b", b["magenta"]),
        ("#928374", b["black"]),
    ]
    text = original
    placeholders = [f"\x00{i}\x00" for i in range(len(roles))]
    for (current_hex, _new_hex), token in zip(roles, placeholders):
        text = text.replace(current_hex, token)
    for (_current_hex, new_hex), token in zip(roles, placeholders):
        text = text.replace(token, new_hex)
    return text


